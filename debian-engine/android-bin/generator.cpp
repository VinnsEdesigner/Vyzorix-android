// generator — turns apis.txt into the catalog source and the command symlinks.
//
// Run at build time, on the host, before the binary is compiled and after it is
// linked:
//
//   generator --apis apis.txt --catalog-out build/api_catalog.cpp
//   generator --apis apis.txt --symlink-dir build/bin --target android-bin
//
// Two responsibilities, one tool, because they must read the same list: the catalog
// the binary prints and the symlinks the build creates cannot disagree if they come
// from one pass over one file.
//
// Why a build step rather than committed files: the API surface grows, and a
// hand-maintained list of 120 symlinks plus a parallel C array is exactly the thing
// that drifts. apis.txt is the single source; this derives the rest.

#include <algorithm>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

#include <sys/stat.h>
#include <unistd.h>

namespace {

/** The names from apis.txt: comments and blanks stripped, order preserved. */
std::vector<std::string> ReadApis(const std::string &path) {
    std::ifstream in(path);
    if (!in) {
        throw std::runtime_error("cannot open " + path);
    }

    std::vector<std::string> names;
    std::string line;

    while (std::getline(in, line)) {
        const std::size_t comment = line.find('#');
        if (comment != std::string::npos) {
            line.erase(comment);
        }

        // Trim surrounding whitespace (spaces and tabs; no locale).
        const std::size_t first = line.find_first_not_of(" \t\r\n");
        if (first == std::string::npos) {
            continue;
        }
        const std::size_t last = line.find_last_not_of(" \t\r\n");
        const std::string name = line.substr(first, last - first + 1);

        if (std::find(names.begin(), names.end(), name) != names.end()) {
            throw std::runtime_error("duplicate api name in " + path + ": " + name);
        }
        // A name becomes a filename and an argv[0], so keep it to the safe set.
        for (const char c : name) {
            const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
                            (c >= '0' && c <= '9') || c == '_';
            if (!ok) {
                throw std::runtime_error("api name has a non-portable character: " + name);
            }
        }

        names.push_back(name);
    }

    if (names.empty()) {
        throw std::runtime_error(path + " lists no APIs");
    }

    return names;
}

/** Writes the generated catalog translation unit. */
void WriteCatalog(const std::string &path, const std::vector<std::string> &names) {
    std::ofstream out(path);
    if (!out) {
        throw std::runtime_error("cannot write " + path);
    }

    out << "// Generated by generator.cpp from apis.txt. Do not edit.\n"
        << "\n"
        << "#include \"api_catalog.h\"\n"
        << "\n"
        << "#include <cstring>\n"
        << "\n"
        << "const char *const kApiNames[] = {\n";
    for (const std::string &name : names) {
        out << "    \"" << name << "\",\n";
    }
    out << "};\n"
        << "\n"
        << "const std::size_t kApiNameCount = " << names.size() << ";\n"
        << "\n"
        << "bool IsKnownApi(const char *name) {\n"
        << "    if (name == nullptr) {\n"
        << "        return false;\n"
        << "    }\n"
        << "    for (std::size_t i = 0; i < kApiNameCount; i++) {\n"
        << "        if (std::strcmp(kApiNames[i], name) == 0) {\n"
        << "            return true;\n"
        << "        }\n"
        << "    }\n"
        << "    return false;\n"
        << "}\n";

    if (!out) {
        throw std::runtime_error("failed while writing " + path);
    }
}

/**
 * Creates `dir/<name> -> target` for every name.
 *
 * The symlink target is a bare basename, not a path, so the whole `bin` directory
 * can be relocated (it is built in the repo and installed into the rootfs overlay).
 * A stale symlink from a previous run is replaced.
 */
void WriteSymlinks(const std::string &dir, const std::string &target,
                   const std::vector<std::string> &names) {
    if (::mkdir(dir.c_str(), 0755) != 0 && errno != EEXIST) {
        throw std::runtime_error("cannot create " + dir);
    }

    for (const std::string &name : names) {
        const std::string link = dir + "/" + name;

        // unlink then symlink: symlink() refuses an existing path, and a leftover
        // from a previous build (or a name that used to be a real file) must go.
        if (::unlink(link.c_str()) != 0 && errno != ENOENT) {
            throw std::runtime_error("cannot clear " + link);
        }
        if (::symlink(target.c_str(), link.c_str()) != 0) {
            throw std::runtime_error("cannot symlink " + link + " -> " + target);
        }
    }
}

} // namespace

int main(int argc, char **argv) {
    std::string apis;
    std::string catalog_out;
    std::string symlink_dir;
    std::string target = "android-bin";

    for (int i = 1; i < argc; i++) {
        const std::string arg = argv[i];
        const auto value = [&](const char *what) -> std::string {
            if (i + 1 >= argc) {
                throw std::runtime_error(std::string(what) + " needs an argument");
            }

            return argv[++i];
        };

        if (arg == "--apis") {
            apis = value("--apis");
        } else if (arg == "--catalog-out") {
            catalog_out = value("--catalog-out");
        } else if (arg == "--symlink-dir") {
            symlink_dir = value("--symlink-dir");
        } else if (arg == "--target") {
            target = value("--target");
        } else {
            std::cerr << "generator: unknown argument " << arg << "\n";

            return 2;
        }
    }

    if (apis.empty()) {
        std::cerr << "generator: --apis is required\n";

        return 2;
    }

    try {
        const std::vector<std::string> names = ReadApis(apis);

        if (!catalog_out.empty()) {
            WriteCatalog(catalog_out, names);
        }
        if (!symlink_dir.empty()) {
            WriteSymlinks(symlink_dir, target, names);
        }

        std::cout << "generator: " << names.size() << " api(s)\n";

        return 0;
    } catch (const std::exception &e) {
        std::cerr << "generator: " << e.what() << "\n";

        return 1;
    }
}
